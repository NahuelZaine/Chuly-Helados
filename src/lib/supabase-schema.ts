export const SUPABASE_TABLES = [
  'categories',
  'products',
  'users',
  'sales',
  'sale_details',
  'sale_payments',
  'expenses',
  'promotions',
  'settings',
  'pos_points',
  'cash_shifts'
] as const;

export const SUPABASE_SQL_SCHEMA = `-- ==============================================================================
-- SCHEMA SQL PARA SUPABASE (Chuly Helados / GelatoFlow)
-- Proyecto: zsirhvqjatpjulyllwtb.supabase.co
-- ==============================================================================

-- 1. Categorías
CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Productos
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
  cost NUMERIC DEFAULT 0,
  price NUMERIC NOT NULL,
  stock_quantity NUMERIC DEFAULT 0,
  unit TEXT DEFAULT 'un',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Usuarios y Cajeros
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'empleado',
  password TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Ventas
CREATE TABLE IF NOT EXISTS public.sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  total NUMERIC NOT NULL,
  payment_method TEXT NOT NULL,
  user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Detalles de Venta
CREATE TABLE IF NOT EXISTS public.sale_details (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id BIGINT REFERENCES public.sales(id) ON DELETE CASCADE,
  product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
  quantity NUMERIC NOT NULL,
  subtotal NUMERIC NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Pagos de Venta (Efectivo, Tarjeta, Transferencia, Mixtos)
CREATE TABLE IF NOT EXISTS public.sale_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id BIGINT REFERENCES public.sales(id) ON DELETE CASCADE,
  method TEXT NOT NULL,
  amount NUMERIC NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Gastos
CREATE TABLE IF NOT EXISTS public.expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  description TEXT NOT NULL,
  amount NUMERIC NOT NULL,
  payment_method TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Promociones
CREATE TABLE IF NOT EXISTS public.promotions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE,
  quantity_threshold INT NOT NULL,
  promo_price NUMERIC NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Configuraciones del Sistema (Impresora, Negocio, Tipografía)
CREATE TABLE IF NOT EXISTS public.settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Puntos de Venta (Terminales y Cajas Registradoras)
CREATE TABLE IF NOT EXISTS public.pos_points (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  label TEXT,
  description TEXT,
  active INT DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. Turnos y Cierres de Caja (Arqueo de Efectivo, Tarjetas y Transferencias)
CREATE TABLE IF NOT EXISTS public.cash_shifts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pos_point_id BIGINT REFERENCES public.pos_points(id) ON DELETE SET NULL,
  pos_point_name TEXT,
  user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  user_name TEXT,
  opened_at TIMESTAMPTZ DEFAULT NOW(),
  closed_at TIMESTAMPTZ,
  initial_cash NUMERIC NOT NULL DEFAULT 0,
  final_cash NUMERIC,
  expected_cash NUMERIC,
  difference NUMERIC,
  total_cash_sales NUMERIC DEFAULT 0,
  total_card_sales NUMERIC DEFAULT 0,
  total_transfer_sales NUMERIC DEFAULT 0,
  total_expenses NUMERIC DEFAULT 0,
  total_sales NUMERIC DEFAULT 0,
  transaction_count INT DEFAULT 0,
  status TEXT DEFAULT 'open',
  notes TEXT
);

-- ==============================================================================
-- POLÍTICAS DE ACCESO ROW LEVEL SECURITY (RLS)
-- Permitir lectura, inserción, actualización y eliminación para clientes anon / pos
-- ==============================================================================

ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sales ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sale_details ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sale_payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.promotions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pos_points ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cash_shifts ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public access categories" ON public.categories;
CREATE POLICY "Public access categories" ON public.categories FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access products" ON public.products;
CREATE POLICY "Public access products" ON public.products FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access users" ON public.users;
CREATE POLICY "Public access users" ON public.users FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access sales" ON public.sales;
CREATE POLICY "Public access sales" ON public.sales FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access sale_details" ON public.sale_details;
CREATE POLICY "Public access sale_details" ON public.sale_details FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access sale_payments" ON public.sale_payments;
CREATE POLICY "Public access sale_payments" ON public.sale_payments FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access expenses" ON public.expenses;
CREATE POLICY "Public access expenses" ON public.expenses FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access promotions" ON public.promotions;
CREATE POLICY "Public access promotions" ON public.promotions FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access settings" ON public.settings;
CREATE POLICY "Public access settings" ON public.settings FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access pos_points" ON public.pos_points;
CREATE POLICY "Public access pos_points" ON public.pos_points FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access cash_shifts" ON public.cash_shifts;
CREATE POLICY "Public access cash_shifts" ON public.cash_shifts FOR ALL USING (true) WITH CHECK (true);
`;
